"""Rebuild every case file, and the case index, from recorded runs. No key, no network."""

from __future__ import annotations

from pathlib import Path

from casebook.records import Run, load_run
from casebook.render import _table, _verdict, render_case


def render_index(runs: list[Run]) -> str:
    rows = []
    for run in runs:
        dec = run.decision
        if dec is None:
            outcome, final = "Awaiting decision", "-"
        else:
            outcome = "Agree" if dec.agrees_with(run.assessment) else "**Override**"
            final = _verdict(dec.verdict)
        det = run.alert["detection"]
        rows.append([
            f"[{run.case_id}]({run.case_id}.md)",
            det["technique_id"],
            f"{_verdict(run.assessment.verdict)} ({run.assessment.confidence})",
            final,
            outcome,
        ])
    lines = [
        "# Cases",
        "",
        "Generated by `casebook replay` from `runs/`. Do not edit by hand.",
        "",
        *_table(["Case", "Technique", "AI verdict (confidence)", "Final verdict", "Outcome"],
                rows),
    ]
    return "\n".join(lines) + "\n"


def replay(runs_dir: Path, cases_dir: Path, check: bool = False) -> list[str]:
    """Write (or, with check=True, compare) case files. Returns the names that differ."""
    runs = [load_run(p) for p in sorted(runs_dir.glob("*.json"))]
    expected = {f"{r.case_id}.md": render_case(r) for r in runs}
    if runs:
        expected["README.md"] = render_index(runs)

    stale = []
    for name, text in expected.items():
        path = cases_dir / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    return stale

